export async function seedEnterpriseDatabaseIfEmpty(): Promise<boolean> {
  try {
    const teamsCol = collection(db, 'teams');
    const existing = await getDocs(query(teamsCol, limit(1)));
    
    if (!existing.empty) {
      console.log('Database already contains enterprise seed records.');
      return false;
    }

    return await seedEnterpriseData();
  } catch (err) {
    console.error('Error checking enterprise database:', err);
    return false;
  }
}

